android {
    namespace = "dev.nexus.control"

    // 37 rather than the 36.1 platform that was already installed locally: several of the
    // AndroidX libraries below declare that consumers must compile against 37 or later, and AGP
    // fetches the platform on demand. compileSdk only affects which APIs are visible at compile
    // time; minSdk below is what governs which devices can install this.
    compileSdk = 37

    defaultConfig {
        applicationId = "dev.nexus.control"

        // Android 12. Chosen so the app can use platform features it actually relies on —
        // Material You dynamic colour and the modern Keystore/BiometricPrompt behaviour — rather
        // than the lowest number that would still compile. This is one owner's own phone; breadth
        // of device support is not a goal.
        minSdk = 31
        targetSdk = 37

        versionCode = 11
        versionName = "1.1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    buildTypes {
        debug {
            // The only build type that matters for v0.5: the owner installs this directly.
            isMinifyEnabled = false
        }
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}")
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

/**
 * Cross-language protocol vectors.
 *
 * The file is generated by the PC Core test suite and lives at the repository root, shared by both
 * sides. The Kotlin unit tests read it straight from there as a test resource rather than from a
 * copy inside this module, so the two implementations can never be checked against different
 * vectors: if PC Core regenerates the file, the next Android test run sees the new one.
 */
android.sourceSets.getByName("test").resources.directories.add(
    rootProject.layout.projectDirectory.dir("../../shared/protocol").asFile.absolutePath,
)

